import { chromium } from "@playwright/test";
import { installNavegadorWallet } from "./navegador-wallet.mjs";
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 960 }, locale: "es-ES" });
await installNavegadorWallet(context, { privateKey: "0x8b3a350cf5c34c9194ca85829a2df0ec3153be0318b5e2d3348e872092edffba" });
const page = await context.newPage();
page.on("console", m => { if (m.type()==="error") console.log("[console]", m.text().slice(0,150)); });
page.on("response", async r => { if (r.url().includes("/api/qr/")) console.log("[qr res]", r.status(), (await r.text().catch(()=>"")).slice(0,200)); });
await page.goto("https://hotel-mcp-web-d6jlzeq5yq-ew.a.run.app/mis-noches", { waitUntil: "domcontentloaded", timeout: 90000 });
await page.waitForTimeout(6000);
const tokenId = "11620261110";
console.log("card", await page.getByTestId(`my-night-${tokenId}`).count());
await page.getByTestId(`ticket-issue-${tokenId}`).click();
await page.waitForTimeout(8000);
const ids = await page.locator('[data-testid]').evaluateAll(els => [...new Set(els.map(e=>e.getAttribute("data-testid")))].filter(x=>x.includes("ticket")));
console.log("ticket ids", ids);
const err = await page.locator('[data-testid^="ticket-error-"]').allTextContents().catch(()=>[]);
console.log("errors", err);
const jws = await page.getByTestId(`ticket-jws-${tokenId}`).textContent().catch(e=>"ERR "+e.message.slice(0,60));
console.log("jws", (jws||"").slice(0,150));
await page.screenshot({ path: "/tmp/ticket-debug.png", fullPage: false });
await browser.close();
